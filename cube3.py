def est_resolu3(cube):
    return all(len(set(cube[i:i+9])) == 1 for i in range(0, 54, 9))

def appliquer3(etat_actuelle, mouv):
    perm = MOUVEMENTS3[mouv]
    return (tuple(etat_actuelle[i] for i in perm))

def repeter3(etat_actuelle, mouv, n):
    for _ in range(n):
        etat_actuelle = appliquer3(etat_actuelle, mouv)
    return etat_actuelle

def melanger3(n,seed):
    etat = RESOLU3
    mouv=[]
    rng = random.Random(seed)
    for _ in range(n):
        nom = rng.choice(list(MOUVEMENTS3))
        etat = appliquer3(etat, nom)
        mouv.append(nom)
    res = [etat,mouv]
    return res

